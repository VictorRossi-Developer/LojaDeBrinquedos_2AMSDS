CREATE DATABASE LojaDeBrinquedos;
GO 

USE LojaDeBrinquedos;
GO

CREATE TABLE ESTOQUE(
    ID_ESTOQUE INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
    QUANTIDADE INT,
    CAPACIDADE INT
);

CREATE TABLE PRODUTO(
    ID_PRODUTO INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
    MARCA VARCHAR(25),
    TIPO VARCHAR(40),
    DESCRICAO VARCHAR(150),

    ID_ESTOQUE INT,

    CONSTRAINT FK_PRODUTO_ESTOQUE FOREIGN KEY (ID_ESTOQUE)
    REFERENCES ESTOQUE(ID_ESTOQUE)
);

CREATE TABLE FORNECEDOR(
    ID_FORNECEDOR INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
    DATA_EMISSAO DATE,
    DATA_ENTREGA DATE,
    TELEFONE VARCHAR(13),
    ENDERECO VARCHAR(255), 

    ID_PRODUTO INT,
    CONSTRAINT FK_FORNECEDOR_PRODUTO FOREIGN KEY (ID_PRODUTO)
    REFERENCES PRODUTO(ID_PRODUTO)
);

CREATE TABLE CLIENTE(
    ID_CLIENTE INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
    NOME VARCHAR(50),
    CPF VARCHAR(11),
    TELEFONE VARCHAR(13),
    ENDERECO VARCHAR(255) 
);

CREATE TABLE COMPRA(
    DATACOMPRA DATE,
    VALOR DECIMAL(10,2), 
    TROCAPRAZO DATE,

    ID_CLIENTE INT,
    CONSTRAINT FK_COMPRA_CLIENTE FOREIGN KEY (ID_CLIENTE)
    REFERENCES CLIENTE(ID_CLIENTE)
);

CREATE TABLE NOTAFISC4AL (
    ID_NOTA INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
    PARCELAS INT,
    VALOR DECIMAL(10,2), 
    DAT_EMISSAO DATE
);
